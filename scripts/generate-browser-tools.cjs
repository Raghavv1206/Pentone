// Generated wrappers retain the existing handler + spec tool-module pattern.
const fs = require("node:fs")
const path = require("node:path")
const { buildSync } = require("esbuild")
const root = path.resolve(__dirname, "..")
const output = path.join(root, "tests/evidence/browser-catalog.cjs")
buildSync({
  entryPoints: [path.join(root, "lib/browser/index.ts")],
  outfile: output,
  bundle: true,
  platform: "node",
  format: "cjs"
})
const { browserTools } = require(output)
for (const tool of browserTools) {
  const name = tool.spec.name
  fs.writeFileSync(
    path.join(root, "lib/tools", `${name}.ts`),
    `// Generated by scripts/generate-browser-tools.cjs\nimport { browserTools } from '../browser'\nconst tool = browserTools.find(tool => tool.spec.name === '${name}')!\nexport const spec = tool.spec\nexport default tool.run\n`
  )
}
console.log(`Generated ${browserTools.length} browser tool modules`)
const categories = [...new Set(browserTools.map((tool) => tool.category))]
const rows = categories.map(
  (category) =>
    `| ${category} | ${browserTools
      .filter((tool) => tool.category === category)
      .map((tool) => "`" + tool.spec.name + "`")
      .join(", ")} |`
)
fs.writeFileSync(
  path.join(root, "docs/browser-tool-catalog.md"),
  `# Additional browser tools\n\nGenerated from the registered schemas. ${browserTools.length} additive tools, alongside the 38 existing tools. Use \`getBrowserTools\` for exact parameter schemas at runtime.\n\n| Category | Tools |\n| --- | --- |\n${rows.join("\n")}\n`
)
